#!/usr/bin/env python3
"""Generate deterministic, independent RTLIL micro fixtures and expectations.

This is test data construction, not a proof engine or a Pass implementation.
All bit positions in the manifest are physical, zero-based RTLIL port bits.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "tests" / "pmux_m1" / "micro"


class Design:
    def __init__(self):
        self.wires = []
        self.cells = []
        self.counter = 0

    def wire(self, name, width=1, direction=None):
        attr = f" {direction} {len([w for w in self.wires if w[2]]) + 1}" if direction else ""
        self.wires.append((name, width, direction, attr))
        return "\\" + name

    def cell(self, kind, name, params, ports):
        lines = [f"  cell ${kind} \\{name}"]
        lines += [f"    parameter \\{k} {v}" for k, v in params.items()]
        lines += [f"    connect \\{k} {v}" for k, v in ports.items()]
        lines.append("  end")
        self.cells.extend(lines)

    def logic(self, kind, a, b=None, width=1, name=None):
        name = name or f"t{self.counter}"
        self.counter += 1
        y = self.wire(name, width)
        if kind == "not":
            self.cell("not", name + "_gate", {"A_SIGNED": 0, "A_WIDTH": width, "Y_WIDTH": width}, {"A": a, "Y": y})
        else:
            self.cell(kind, name + "_gate", {"A_SIGNED": 0, "B_SIGNED": 0,
                  "A_WIDTH": width, "B_WIDTH": width, "Y_WIDTH": width}, {"A": a, "B": b, "Y": y})
        return y

    def compare(self, kind, x, constant, width, name="cmp", a_width=None, b_width=None, a_signed=0, b_signed=0):
        s = self.wire(name)
        aw, bw = a_width or width, b_width or width
        self.cell(kind, name + "_gate", {"A_SIGNED": a_signed, "B_SIGNED": b_signed,
                  "A_WIDTH": aw, "B_WIDTH": bw, "Y_WIDTH": 1},
                  {"A": x, "B": f"{bw}'{constant:0{bw}b}", "Y": s})
        return s

    def logic_not(self, source, source_width, name):
        result = self.wire(name)
        self.cell("logic_not", name + "_gate", {"A_SIGNED": 0,
                  "A_WIDTH": source_width, "Y_WIDTH": 1}, {"A": source, "Y": result})
        return result

    def mux(self, a, b, s, width=1, name="target"):
        y = self.wire("out", width, "output")
        self.cell("mux", name, {"WIDTH": width}, {"A": a, "B": b, "S": s, "Y": y})

    def pmux(self, a, b, s, width, branches, name="target"):
        y = self.wire("out", width, "output")
        self.cell("pmux", name, {"WIDTH": width, "S_WIDTH": branches},
                  {"A": a, "B": b, "S": s, "Y": y})

    def render(self):
        lines = ["# Generated by pmux_project/scripts/generate_micro.py", "module \\top"]
        for name, width, _, attr in self.wires:
            lines.append(f"  wire width {width}{attr} \\{name}")
        lines.extend(self.cells)
        lines.append("end")
        return "\n".join(lines) + "\n"


def case(case_id, d, edits=(), reason="none", trigger=False, note="", budget=None):
    return case_id, d, {"id": case_id, "file": case_id + ".il", "top": "top",
                          "trigger": trigger, "expected_edits": [
                              {"module": "top", "cell": "target", "port": p,
                               "bit": i, "value": v, "branch": branch}
                              for p, i, v, branch in edits],
                          "reason_code": reason, "structure": "PASS",
                          "eqy": "PASS", "note": note, "budget": budget}


def make():
    cases = []
    d = Design(); x=d.wire("x",direction="input"); q=d.wire("q",direction="input"); d.mux(x,q,x)
    cases.append(case("01_mux_a",d,[("A",0,"0",None)],trigger=True))
    d = Design(); x=d.wire("x",direction="input"); q=d.wire("q",direction="input"); d.mux(q,x,x)
    cases.append(case("02_mux_b",d,[("B",0,"1",None)],trigger=True))
    d = Design(); x=d.wire("x",direction="input"); y=d.wire("y",direction="input"); q=d.wire("q",direction="input"); a=d.logic("and",x,y); d.pmux(a,"{ \\q \\q }", "{ \\y \\x }",1,2)
    cases.append(case("03_pmux_a",d,[("A",0,"0",None)],trigger=True))
    d = Design(); x=d.wire("x",direction="input"); y=d.wire("y",direction="input"); q=d.wire("q",direction="input"); d.pmux(q,"{ \\q \\x }","{ \\y \\x }",1,2)
    cases.append(case("04_pmux_bi",d,[("B",0,"1",0)],trigger=True))
    d = Design(); x=d.wire("x",4,"input"); q=d.wire("q",4,"input"); s=d.compare("eq",x,10,4); d.mux(q,x,s,4)
    cases.append(case("05_eq_reverse",d,[("B",i,str((10>>i)&1),None) for i in range(4)],trigger=True))
    d = Design(); x=d.wire("x",4,"input"); q=d.wire("q",4,"input"); s=d.compare("ne",x,5,4); d.mux(x,q,s,4)
    cases.append(case("06_ne_zero_reverse",d,[("A",i,str((5>>i)&1),None) for i in range(4)],trigger=True))
    d = Design(); x=d.wire("x",direction="input"); q=d.wire("q",direction="input"); a=d.wire("a",2,"input"); d.mux(a,"{ \\q \\x }",x,2)
    cases.append(case("07_partial_bit",d,[("B",0,"1",None)],trigger=True,note="B[1] remains unknown"))
    d = Design(); x=d.wire("x",direction="input"); q=d.wire("q",direction="input"); d.wire("shared",direction="output"); d.cells.append("  connect \\shared \\x"); d.mux(q,x,x)
    cases.append(case("08_shared_source",d,[("B",0,"1",None)],trigger=True,note="Shared output must still use x"))
    d = Design(); x=d.wire("x",direction="input"); y=d.wire("y",direction="input"); q=d.wire("q",direction="input"); d.pmux(q,"{ \\y \\x }","{ \\y \\x }",1,2)
    cases.append(case("09_overlap_pmux",d,[("B",0,"1",0),("B",1,"1",1)],trigger=True,note="No one-hot assumption; priority unchanged"))
    d = Design(); x=d.wire("x",direction="input"); q=d.wire("q",3,"input"); d.mux(q,"{ 2'xz \\x }",x,3)
    cases.append(case("10_xz_untouched",d,[("B",0,"1",None)],reason="original_xz",trigger=True,note="B[1:2] are original x/z"))
    d = Design(); x=d.wire("x",2,"input"); q=d.wire("q",2,"input"); s=d.compare("eq",x,15,2,a_width=2,b_width=4,a_signed=1,b_signed=1); d.mux(q,x,s,2)
    cases.append(case("11_ambiguous_compare",d,reason="primary_input",note="Signed 2-to-4 extension repeats a source bit; no reverse inference, target x stays a primary input"))
    d = Design(); x=d.wire("x",direction="input"); y=d.wire("y",direction="input"); q=d.wire("q",direction="input"); g=d.wire("g",direction="input"); u=d.logic("xor",x,y); d.mux(q,u,g)
    cases.append(case("12_unsupported_cell",d,reason="unsupported_cell"))
    d = Design(); x=d.wire("x",direction="input"); q=d.wire("q",direction="input"); nx=d.logic("not",x); s=d.logic("and",x,nx); d.mux(q,x,s)
    cases.append(case("13_fact_conflict",d,reason="fact_conflict",note="Guard S=1 contradicts x & !x"))
    d = Design(); x=d.wire("x",direction="input"); q=d.wire("q",direction="input"); v=x
    for i in range(513): v=d.logic("not",v,name=f"chain{i}")
    d.mux(q,x,v)
    cases.append(case("14a_budget_cells",d,reason="budget_cells_exhausted",budget={"cell_limit":512},note="513-cell control dependency"))
    d = Design(); x=d.wire("x",8193,"input"); q=d.wire("q",8193,"input"); s=d.compare("eq",x,0,8193); d.mux(q,x,s,8193)
    cases.append(case("14b_budget_bits",d,reason="budget_bits_exhausted",budget={"bit_limit":8192},note="8193 normalized control/data bits"))
    d = Design(); s=d.wire("event_guard",512,"input"); free=d.wire("free",direction="input")
    outputs=[d.logic_not(s,512,f"event_y{i}") for i in range(512)]
    a="{ " + free + " " + " ".join(reversed(outputs)) + " }"
    d.pmux(a,"262656'" + "0"*262656,s,513,512)
    cases.append(case("14c_budget_events",d,
                      [("A",i,"1",None) for i in range(512)],trigger=True,
                      reason="budget_events_exhausted",
                      budget={"event_limit":262144},
                      note="A's published slow-test topology plus one unresolved free bit; retain 512 complete proofs and leave A[512] unchanged"))
    d = Design(); x=d.wire("x",direction="input"); y=d.wire("y",direction="input"); q=d.wire("q",direction="input"); d.pmux(q,"{ \\y \\x }","{ \\y \\x }",1,2)
    cases.append(case("15_multi_branch_merge",d,[("B",0,"1",0),("B",1,"1",1)],trigger=True))
    d = Design(); x=d.wire("x",direction="input"); a=d.wire("a",direction="input"); b=d.wire("b",direction="input"); d.mux(a,b,x)
    cases.append(case("16_no_opportunity",d,reason="primary_input"))
    d = Design(); x=d.wire("x",8,"input"); q=d.wire("q",8,"input"); d.wire("shared",8,"output"); d.cells.append("  connect \\shared \\x"); s=d.compare("eq","\\x [6:0]",0b1010110,7); d.mux(q,x,s,8)
    cases.append(case("17_case3_seven_bits",d,[("B",i,str((0b1010110>>i)&1),None) for i in range(7)],trigger=True,note="Seven located comparator bits; B[7] and shared output unchanged"))
    return cases


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    cases = make()
    for name,d,_ in cases: (OUT / (name + ".il")).write_text(d.render())
    (OUT / "expectations.json").write_text(json.dumps({"schema":1,"cases":[c[2] for c in cases]},indent=2,ensure_ascii=False)+"\n")
    print(f"generated {len(cases)} independent fixtures in {OUT}")


if __name__ == "__main__": main()
